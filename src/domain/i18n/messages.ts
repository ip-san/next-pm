const MESSAGES: Record<Locale, Record<MessageKey, string>> = { ja: JA, en: EN };

/** The text for a key in a locale. Every key exists in every locale (the type requires it). */
export function translate(locale: Locale, key: MessageKey): string {
  return MESSAGES[locale][key];
}

/** Fills the `{name}` placeholders of a translated string. A placeholder with no value is left as written. */
export function interpolate(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) => (name in values ? String(values[name]) : placeholder));
}
